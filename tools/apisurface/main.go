//go:build ignore

// Command apisurface prints the exported API surface of the package in the
// target directory (default ".") and of its public subpackages as a
// deterministic, sorted text report. A subpackage's lines qualify the owner
// with the package name ("func html.Document(...)").
//
// It is intentionally excluded from normal builds via the //go:build ignore
// constraint and depends only on the standard library (go/ast, go/parser,
// go/printer, go/token). Run it and commit the output as the golden file:
//
//	go run tools/apisurface/main.go > api-surface.txt
//
// CI regenerates this file and fails on any diff, catching accidental changes
// to the public API.
//
// Grammar: one exported symbol or member per line, "<kind> <owner> [<rest>]",
// single spaces, fully sorted, lines starting with '#' are comments:
//
//	const Version string                 (never the value: it changes per release)
//	func New(token string, opts ...Option) (*Client, error)
//	type ScrapeConfig struct
//	field ScrapeConfig URL string
//	method Client.Do(ctx context.Context, ...) (*Result, error)
//	method Iface.M(...) [required]       (a method of an exported interface)
//
// A line suffixed " [required]" is one whose addition breaks existing callers
// (a method added to an interface they implement). The format lets a
// release tool diff two goldens line by line: a removed line is a breaking
// change, an added one an addition.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	out, err := surface(dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "apisurface:", err)
		os.Exit(1)
	}
	if _, err := os.Stdout.WriteString(out); err != nil {
		fmt.Fprintln(os.Stderr, "apisurface:", err)
		os.Exit(1)
	}
}

func surface(dir string) (string, error) {
	lines, name, err := packageLines(dir)
	if err != nil {
		return "", err
	}
	subs, err := subpackageDirs(dir)
	if err != nil {
		return "", err
	}
	for _, sub := range subs {
		subLines, subName, err := packageLines(filepath.Join(dir, sub))
		if err != nil {
			return "", err
		}
		for _, l := range subLines {
			kind, rest, _ := strings.Cut(l, " ")
			lines = append(lines, kind+" "+subName+"."+rest)
		}
	}
	sort.Strings(lines)

	var b strings.Builder
	fmt.Fprintln(&b, "# sdo-go public API surface")
	fmt.Fprintln(&b, "# Generated by tools/apisurface (go run tools/apisurface/main.go). DO NOT EDIT.")
	fmt.Fprintln(&b, "# Regenerate and commit this file whenever the exported API changes.")
	if mod := modulePath(dir); mod != "" {
		fmt.Fprintf(&b, "# module %s\n", mod)
	}
	fmt.Fprintf(&b, "# package %s\n", name)
	for _, sub := range subs {
		fmt.Fprintf(&b, "# package %s\n", filepath.ToSlash(sub))
	}
	for _, l := range lines {
		b.WriteString(l)
		b.WriteString("\n")
	}
	return b.String(), nil
}

// subpackageDirs lists the public subpackages below dir: directories holding
// non-test Go files, except tools, testdata, internal and hidden ones.
func subpackageDirs(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if !d.IsDir() || path == dir {
			return nil
		}
		switch name := d.Name(); {
		case name == "tools", name == "testdata", name == "internal", strings.HasPrefix(name, "."), strings.HasPrefix(name, "_"):
			return filepath.SkipDir
		}
		entries, err := os.ReadDir(path)
		if err != nil {
			return err
		}
		for _, e := range entries {
			if n := e.Name(); strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") {
				rel, err := filepath.Rel(dir, path)
				if err != nil {
					return err
				}
				out = append(out, rel)
				break
			}
		}
		return nil
	})
	sort.Strings(out)
	return out, err
}

// packageLines returns the unsorted surface lines of the package in dir and
// its name.
func packageLines(dir string) ([]string, string, error) {
	fset := token.NewFileSet()
	// Exclude test files so the golden reflects only the shipped API surface.
	notTest := func(fi os.FileInfo) bool { return !strings.HasSuffix(fi.Name(), "_test.go") }
	pkgs, err := parser.ParseDir(fset, dir, notTest, parser.ParseComments)
	if err != nil {
		return nil, "", err
	}
	pkg := selectPackage(pkgs)
	if pkg == nil {
		return nil, "", fmt.Errorf("no non-test package found in %s", dir)
	}

	var lines []string
	exported := map[string]bool{} // exported type names, to attach methods
	type pendingMethod struct{ base, line string }
	var methods []pendingMethod

	for _, file := range pkg.Files {
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.GenDecl:
				switch d.Tok {
				case token.CONST:
					lines = append(lines, valueSpecs(fset, d, "const")...)
				case token.VAR:
					lines = append(lines, valueSpecs(fset, d, "var")...)
				case token.TYPE:
					for _, spec := range d.Specs {
						ts := spec.(*ast.TypeSpec)
						if !ts.Name.IsExported() {
							continue
						}
						exported[ts.Name.Name] = true
						lines = append(lines, describeType(fset, ts)...)
					}
				}
			case *ast.FuncDecl:
				if !d.Name.IsExported() {
					continue
				}
				if d.Recv == nil {
					lines = append(lines, "func "+d.Name.Name+signature(fset, d.Type))
					continue
				}
				if base := embeddedName(d.Recv.List[0].Type); base != "" {
					methods = append(methods, pendingMethod{base,
						fmt.Sprintf("method %s.%s%s", base, d.Name.Name, signature(fset, d.Type))})
				}
			}
		}
	}
	for _, m := range methods {
		if exported[m.base] {
			lines = append(lines, m.line)
		}
	}
	return lines, pkg.Name, nil
}

// valueSpecs renders exported const/var names with their type, never their
// value. A block may omit the type on trailing specs (iota style); the last
// explicit type is inherited. Untyped constants get their literal's default
// type.
func valueSpecs(fset *token.FileSet, d *ast.GenDecl, kw string) []string {
	var out []string
	lastType := ""
	for _, spec := range d.Specs {
		vs, ok := spec.(*ast.ValueSpec)
		if !ok {
			continue
		}
		curType := lastType
		if vs.Type != nil {
			curType = exprString(fset, vs.Type)
			lastType = curType
		}
		for i, name := range vs.Names {
			if !name.IsExported() {
				continue
			}
			typ := curType
			if typ == "" && i < len(vs.Values) {
				typ = literalType(fset, vs.Values[i])
			}
			out = append(out, strings.TrimSpace(fmt.Sprintf("%s %s %s", kw, name.Name, typ)))
		}
	}
	return out
}

// literalType is the default type of an untyped constant expression.
func literalType(fset *token.FileSet, e ast.Expr) string {
	switch v := e.(type) {
	case *ast.BasicLit:
		switch v.Kind {
		case token.STRING:
			return "string"
		case token.INT:
			return "int"
		case token.FLOAT:
			return "float64"
		case token.CHAR:
			return "rune"
		case token.IMAG:
			return "complex128"
		}
	case *ast.CompositeLit:
		return exprString(fset, v.Type)
	case *ast.UnaryExpr:
		if v.Op == token.AND {
			if cl, ok := v.X.(*ast.CompositeLit); ok {
				return "*" + exprString(fset, cl.Type)
			}
		}
	}
	return "untyped"
}

// describeType renders a type declaration line plus one line per exported
// member.
func describeType(fset *token.FileSet, ts *ast.TypeSpec) []string {
	name := ts.Name.Name
	head := "type " + name
	if ts.TypeParams != nil {
		head += "[" + strings.Join(fieldParts(fset, ts.TypeParams), ", ") + "]"
	}
	if ts.Assign.IsValid() {
		head += " ="
	}
	switch t := ts.Type.(type) {
	case *ast.StructType:
		return append([]string{head + " struct"}, structMembers(fset, name, t.Fields)...)
	case *ast.InterfaceType:
		return append([]string{head + " interface"}, interfaceMembers(fset, name, t.Methods)...)
	default:
		return []string{head + " " + exprString(fset, ts.Type)}
	}
}

func structMembers(fset *token.FileSet, owner string, fl *ast.FieldList) []string {
	var out []string
	if fl == nil {
		return out
	}
	for _, f := range fl.List {
		typ := exprString(fset, f.Type)
		if len(f.Names) == 0 { // embedded
			if n := embeddedName(f.Type); n != "" && ast.IsExported(n) {
				out = append(out, fmt.Sprintf("embed %s %s", owner, typ))
			}
			continue
		}
		for _, name := range f.Names {
			if name.IsExported() {
				out = append(out, fmt.Sprintf("field %s %s %s", owner, name.Name, typ))
			}
		}
	}
	return out
}

// interfaceMembers marks every method [required]: adding one breaks every
// caller that implements the interface.
func interfaceMembers(fset *token.FileSet, owner string, fl *ast.FieldList) []string {
	var out []string
	if fl == nil {
		return out
	}
	for _, f := range fl.List {
		if len(f.Names) == 0 { // embedded interface or type-set term
			out = append(out, fmt.Sprintf("embed %s %s [required]", owner, exprString(fset, f.Type)))
			continue
		}
		for _, name := range f.Names {
			if !name.IsExported() {
				continue
			}
			sig := " " + exprString(fset, f.Type)
			if ft, ok := f.Type.(*ast.FuncType); ok {
				sig = signature(fset, ft)
			}
			out = append(out, fmt.Sprintf("method %s.%s%s [required]", owner, name.Name, sig))
		}
	}
	return out
}

// embeddedName returns the leaf identifier of an embedded field type, unwrapping
// pointers and qualified/generic wrappers.
func embeddedName(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		return embeddedName(t.X)
	case *ast.SelectorExpr:
		return t.Sel.Name
	case *ast.IndexExpr:
		return embeddedName(t.X)
	case *ast.IndexListExpr:
		return embeddedName(t.X)
	}
	return ""
}

// signature renders a func type as "(params) results" (leading "func" omitted).
func signature(fset *token.FileSet, ft *ast.FuncType) string {
	return fieldListParens(fset, ft.Params) + results(fset, ft.Results)
}

func fieldListParens(fset *token.FileSet, fl *ast.FieldList) string {
	return "(" + strings.Join(fieldParts(fset, fl), ", ") + ")"
}

func results(fset *token.FileSet, fl *ast.FieldList) string {
	if fl == nil || len(fl.List) == 0 {
		return ""
	}
	parts := fieldParts(fset, fl)
	named := false
	count := 0
	for _, f := range fl.List {
		if len(f.Names) == 0 {
			count++
		} else {
			count += len(f.Names)
			named = true
		}
	}
	if count == 1 && !named {
		return " " + parts[0]
	}
	return " (" + strings.Join(parts, ", ") + ")"
}

func fieldParts(fset *token.FileSet, fl *ast.FieldList) []string {
	var parts []string
	if fl == nil {
		return parts
	}
	for _, f := range fl.List {
		typ := exprString(fset, f.Type)
		if len(f.Names) == 0 {
			parts = append(parts, typ)
			continue
		}
		names := make([]string, 0, len(f.Names))
		for _, n := range f.Names {
			names = append(names, n.Name)
		}
		parts = append(parts, strings.Join(names, ", ")+" "+typ)
	}
	return parts
}

func exprString(fset *token.FileSet, e ast.Expr) string {
	var buf bytes.Buffer
	// printer output is deterministic for identical input; single-line for the
	// type/signature expressions we render here.
	if err := printer.Fprint(&buf, fset, e); err != nil {
		return "?"
	}
	return normalizeSpace(buf.String())
}

// normalizeSpace collapses any internal newline/tab runs into single spaces so a
// multi-line printer rendering (rare, e.g. an inline struct type) stays on one
// line and stays deterministic.
func normalizeSpace(s string) string {
	if !strings.ContainsAny(s, "\n\t") {
		return s
	}
	return strings.Join(strings.Fields(s), " ")
}

// selectPackage returns the sole non-test package, preferring one that is not
// named "main"; iteration order is made deterministic via sorted keys.
func selectPackage(pkgs map[string]*ast.Package) *ast.Package {
	names := make([]string, 0, len(pkgs))
	for name := range pkgs {
		names = append(names, name)
	}
	sort.Strings(names)
	var fallback *ast.Package
	for _, name := range names {
		if strings.HasSuffix(name, "_test") {
			continue
		}
		if fallback == nil {
			fallback = pkgs[name]
		}
		if name != "main" {
			return pkgs[name]
		}
	}
	return fallback
}

func modulePath(dir string) string {
	f, err := os.Open(dir + "/go.mod")
	if err != nil {
		return ""
	}
	defer f.Close()
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if strings.HasPrefix(line, "module ") {
			return strings.TrimSpace(strings.TrimPrefix(line, "module "))
		}
	}
	return ""
}
